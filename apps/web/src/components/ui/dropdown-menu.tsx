// Local edit, of the same kind as the one described at the top of ui/button.tsx
// (re-apply on a re-pull), and spelled in prose rather than in class names
// because Tailwind scans this file as raw text and a utility written out in a
// comment compiles into the bundle as a real rule.
//
// Two things, both about the strip a row paints when it is the one you are on.
//
// It was the tinted fill the generator uses for menu focus and selection: a
// violet at 0.032 chroma in the light theme and 0.045 in the dark. That token
// is still right for the sidebar, where the wash marks the page you are
// standing on and is meant to be a colour. A menu row is not a place, it is the
// item under the pointer for as long as the pointer is there, so it takes the
// same neutral rung every other edgeless control in the app takes, off the same
// two variables in index.css. In light the swap is a pure de-tinting, the two
// fills being 0.92 and 0.921 in value; in dark it also drops the rung back to
// where the rest of the app puts it. Rule 2 in index.css has the argument.
//
// And every fill and ink here is repeated for the pressed state. Base UI drives
// the highlight off focus, which a pointer moves for you and a finger does not,
// so on a phone a menu row went from untouched to gone with nothing in between.

